/**
 * Tiny typed element builder. All text goes through textContent / text nodes,
 * so API data can never be interpreted as HTML (SPEC NFR Security).
 */
type Attrs = Record<string, string | number | boolean | null | undefined>;
type Child = Node | string | null | undefined | false;

export function el<K extends keyof HTMLElementTagNameMap>(
  tag: K,
  attrs: Attrs = {},
  children: Child[] = [],
): HTMLElementTagNameMap[K] {
  const node = document.createElement(tag);
  for (const [key, value] of Object.entries(attrs)) {
    if (value === null || value === undefined || value === false) continue;
    node.setAttribute(key, value === true ? '' : String(value));
  }
  append(node, children);
  return node;
}

export function append(parent: Node, children: Child[]): void {
  for (const child of children) {
    if (child === null || child === undefined || child === false) continue;
    parent.appendChild(typeof child === 'string' ? document.createTextNode(child) : child);
  }
}

/** External link with safe rel attributes. */
export function extLink(href: string, attrs: Attrs, children: Child[]): HTMLAnchorElement {
  return el('a', { href, target: '_blank', rel: 'noopener noreferrer', ...attrs }, children);
}

